import argparse
import difflib
import hashlib
import html
import json
from pathlib import Path
import re
import zipfile

from build_commit_versions_bundle import git, raw_blobs

ROOT = Path(__file__).resolve().parents[1]
COURSE = ROOT / "curso/reconstrucao-primeiro-commit"
OUTPUT = ROOT.parent / "docs/curso-udemy/primeiro-commit"
COMMIT = "f7efe357cdcd4a05e922a5fb205bd8757cdc5625"
STAGES = [
    ("R01", "Estrutura Cargo e main de apresentação", [".gitignore", "Cargo.toml", "Cargo.lock", "src/main.rs"], "fn/main, println!, texto, parâmetros, bloco e ponto e vírgula"),
    ("R02", "Manifesto histórico e bibliotecas", ["Cargo.toml", "Cargo.lock"], "crate, versões, features, TOML, lockfile e compilação travada"),
    ("R03", "Persistência e ator de disco", ["src/persistence/mod.rs", "src/persistence/actor.rs", "src/lib.rs"], "módulo, Result, ownership, mapas, bytes, WAL, fsync, canais e thread"),
    ("R04", "Autenticação e autorização", ["src/auth/mod.rs", "src/lib.rs"], "Serde/TOML, Argon2, fingerprint, salt, ACL e política de acesso"),
    ("R05", "Transporte TCP e TLS", ["src/transport/mod.rs", "src/lib.rs"], "async/await, TcpListener, Semaphore, timeout, TLS/mTLS e tarefa"),
    ("R06", "Núcleo MQTT e biblioteca completa", ["src/mqtt/codec.rs", "src/mqtt/store.rs", "src/mqtt/router.rs", "src/mqtt/mod.rs", "src/lib.rs"], "bytes MQTT, packet-id, QoS, sessão, retained, ator e ACK após commit"),
    ("R07", "Main real do broker", ["src/main.rs"], "variáveis de ambiente, perfil, bind, logging, Arc e atendimento"),
    ("R08", "Programa mqtt-admin", ["src/bin/mqtt-admin/main.rs"], "argumentos, padrão de lista, hash-password, fingerprint e exit code"),
    ("R09", "Programa mqtt-client", ["src/bin/mqtt-client/cli.rs", "src/bin/mqtt-client/credentials.rs", "src/bin/mqtt-client/tls.rs", "src/bin/mqtt-client/session.rs", "src/bin/mqtt-client/main.rs"], "CLI, segredo, validação CA/SAN, rumqttc, pub/sub, poll e timeout"),
    ("R10", "Conteúdo histórico completo e primeiro commit", [], "exemplo, documentação, configuração, validação final e Git"),
]


def original_files():
    names = {}
    for item in git(ROOT, "ls-tree", "-r", "-z", COMMIT).split(b"\0"):
        if not item:
            continue
        fields, raw_name = item.split(b"\t", 1)
        mode, kind, oid = fields.decode().split()
        if mode != "100644" or kind != "blob":
            raise ValueError("Snapshot inicial tem objeto não previsto")
        names[raw_name.decode()] = oid
    return raw_blobs(ROOT, names)


def prepare():
    (COURSE / "prompts").mkdir(parents=True, exist_ok=True)
    for identifier, title, files, concepts in STAGES:
        destination = COURSE / "prompts" / (identifier + ".md")
        if destination.exists():
            continue
        document = f"# {identifier} rev1 — {title}\n\nNovo exercício de reconstrução preparado por P77, não um prompt histórico\noriginal. Destino final: XMQR0.3.0/commit{COMMIT}.\n\nEntrada: etapa anterior preservada (R01 começa com pasta nova).\nObjetivo: {title}. Conceitos a explicar antes de digitar: {concepts}.\nArquivos: {', '.join(files) if files else 'restantes dos35 arquivos originais, sem adicionar fonte extra'}.\n\nDigite o conteúdo completo mostrado no guia e preserve os arquivos mantidos.\nSubstituições de lib/main/manifests pedagógicos são explícitas no diff.\nCódigo histórico não deve ser corrigido silenciosamente ou atribuído a esta\nsequência como autoria original. Guias/comentários explicativos ficam fora de codigo/.\n\nAceite: cargo build --locked --bins e cargo check --locked --all-targets\nWindows e Ubuntu26 em cópias isoladas; hashes da fonte preservados.\nR10: todas as fontes iguais ao primeiro commit; registrar gates e pub/sub\nloopback se ensaiados, sem serviço/estado/credenciais reais.\n\nCargo.lock gerado na base e fornecido histórico desdeR02; não atualizar\ndependências. Arquivos/commit do aluno pertencem a pasta nova de estudo.\n"
        destination.write_text(document, encoding="utf-8")
    print("Preparados dez prompts R01..R10 antes da exportação de código.")


def snapshots(original):
    current, library = {}, []
    for identifier, title, files, concepts in STAGES:
        if identifier == "R01":
            current = {".gitignore": original[".gitignore"], "Cargo.toml": b'[package]\nname = "mqtt-broker"\nversion = "0.1.0"\nedition = "2024"\n\n[dependencies]\n', "Cargo.lock": b'# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "mqtt-broker"\nversion = "0.1.0"\n', "src/main.rs": b'fn main() {\n    println!("XMQR: estrutura inicial em Rust.");\n}\n'}
        elif identifier == "R10":
            current = dict(original)
        else:
            for name in files:
                if name != "src/lib.rs":
                    current[name] = original[name]
            if identifier in {"R03", "R04", "R05"}:
                library.append({"R03": "persistence", "R04": "auth", "R05": "transport"}[identifier])
                current["src/lib.rs"] = ("//! Componentes acrescentados na reconstrução didática.\n\n" + "".join("pub mod " + name + ";\n" for name in sorted(library))).encode()
            elif identifier == "R06":
                current["src/lib.rs"] = original["src/lib.rs"]
        yield identifier, title, dict(current), files, concepts


def export():
    original = original_files()
    OUTPUT.mkdir(parents=True, exist_ok=True)
    previous, catalogue = {}, []
    for identifier, title, files, order, concepts in snapshots(original):
        prompt = (COURSE / "prompts" / (identifier + ".md")).read_bytes()
        changes = {name: "NOVO" if name not in previous else "ALTERADO" if previous[name] != data else "MANTIDO" for name, data in files.items()}
        diff = "".join("".join(difflib.unified_diff(previous.get(name, b"").decode().splitlines(keepends=True), data.decode().splitlines(keepends=True), fromfile="anterior/" + name, tofile=identifier + "/" + name)) for name, data in sorted(files.items()) if previous.get(name) != data)
        info = {"etapa": identifier, "titulo": title, "prompt_didatico": identifier, "prompt_criador_material": "P77", "commit_historico_destino": COMMIT, "arquivos": changes, "sha256_fontes": {name: hashlib.sha256(data).hexdigest() for name, data in files.items()}, "ordem_digitacao": order or sorted(name for name in files if changes[name] != "MANTIDO"), "conceitos": concepts, "zip": identifier + "-projeto-acumulado.zip", "resultado_final_exato": identifier == "R10"}
        instructions = f"# {identifier} — {title}\n\nReconstrução didática nova P77; consulte PROMPT.md e MANIFESTO.json.\n\nDigite os arquivos desta etapa na ordem: {', '.join(info['ordem_digitacao'])}.\nConteúdo completo em codigo/. Não digite números de linha das tabelas do guia.\nPreserve arquivos mantidos; ALTERACOES.diff lista os novos/alterados.\n\nDentro de codigo/: cargo build --locked --bins e cargo check --locked --all-targets.\nR01 imprime apresentação; desdeR07 main inicia broker e exige ambiente configurado.\nNão usar estado/serviços/credenciais reais. Leia o roteiro completo no índiceHTML.\n\nR10 contém exatamente os35 arquivos históricos. Guias e prompts ficam fora de codigo/.\nO primeiro commit que você criar terá outroSHA, embora possa conter os mesmos arquivos.\n"
        with zipfile.ZipFile(OUTPUT / info["zip"], "w", zipfile.ZIP_DEFLATED) as archive:
            for name, data in sorted(files.items()):
                archive.writestr("codigo/" + name, data)
            archive.writestr("PROMPT.md", prompt)
            archive.writestr("README.md", instructions.encode())
            archive.writestr("MANIFESTO.json", json.dumps(info, ensure_ascii=False, indent=2).encode())
            archive.writestr("ALTERACOES.diff", diff.encode())
        with zipfile.ZipFile(OUTPUT / info["zip"]) as verified:
            if verified.testzip() or any(verified.read("codigo/" + name) != data for name, data in files.items()):
                raise ValueError("ZIP não corresponde às fontes")
        info["sha256_zip"] = hashlib.sha256((OUTPUT / info["zip"]).read_bytes()).hexdigest()
        catalogue.append(info)
        previous = files
    if previous != original or len(original) != 35:
        raise ValueError("Resultado final não é o primeiro commit completo")
    (OUTPUT / "indice.json").write_text(json.dumps(catalogue, ensure_ascii=False, indent=2), encoding="utf-8")
    (OUTPUT / "ROTEIRO.md").write_bytes((COURSE / "ROTEIRO.md").read_bytes())
    (OUTPUT / "SHA256SUMS.txt").write_text("".join(info["sha256_zip"] + "  " + info["zip"] + "\n" for info in catalogue), encoding="utf-8")
    print("Exportados dez checkpoints cumulativos; R10 contém exatamente35 arquivos Git.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--prepare", action="store_true")
    args = parser.parse_args()
    prepare() if args.prepare else export()
